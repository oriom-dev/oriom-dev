// Writes src/client/3d/zones.ts: the coordinates of each time zone's principal city, from
// tzdata's zone.tab and zone1970.tab (plus the old names browsers still report, the links
// in tzdata.zi), so
// the 3D sky can stand where the visitor is without asking for their location.
//   node tools/zones.ts $(nix eval --raw nixpkgs#tzdata.outPath)/share/zoneinfo
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node tools/zones.ts <zoneinfo dir>');
const deg = (s: string, w: number) => {
  const sign = s[0] === '-' ? -1 : 1, d = s.slice(1);
  const v = Number(d.slice(0, w)) + Number(d.slice(w, w + 2)) / 60 + Number(d.slice(w + 2, w + 4) || 0) / 3600;
  return Math.round(sign * v * 10) / 10;
};
const at = new Map<string, [number, number]>();
for (const line of ['zone1970.tab', 'zone.tab'].flatMap((f) => readFileSync(path.join(dir, f), 'utf8').split('\n'))) {
  if (!line || line.startsWith('#')) continue;
  const [, coord, name] = line.split('\t');
  const m = /^([+-]\d+)([+-]\d+)$/.exec(coord!)!;
  if (!at.has(name!)) at.set(name!, [deg(m[1]!, 2), deg(m[2]!, 3)]);
}
const REGION = /^(Africa|America|Antarctica|Asia|Atlantic|Australia|Europe|Indian|Pacific)\//;
const alias: [string, string][] = [];
for (const line of readFileSync(path.join(dir, 'tzdata.zi'), 'utf8').split('\n')) {
  const f = line.split(' ');
  if (f[0] === 'L' && REGION.test(f[2]!) && at.has(f[1]!) && !at.has(f[2]!)) alias.push([f[2]!, f[1]!]);
}
const table = [...at].map(([n, [la, lo]]) => `${n} ${la} ${lo}`).join(';');
const links = alias.map(([a, b]) => `${a} ${b}`).join(';');
writeFileSync(path.resolve(import.meta.dirname, '../src/client/3d/zones.ts'),
  `// generated by tools/zones.ts from tzdata: "Zone lat lon" and "Alias Zone"\nexport const ZONES = ${JSON.stringify(table)};\nexport const LINKS = ${JSON.stringify(links)};\n`);
console.log(at.size, 'zones', alias.length, 'links');
